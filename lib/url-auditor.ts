/** Audit a single URL end-to-end */
export async function auditUrl(url: string): Promise<URLAuditResult> {
  const changes: string[] = [];

  console.log(`\n  🌐 Auditing: ${url}`);

  // Step 1: Fetch page signals
  console.log('     📡 Fetching page signals...');
  let signals: PageSignals;
  try {
    signals = await fetchPageSignals(url);
    changes.push(`Fetched ${url} (HTTP ${signals.status})`);
  } catch (e) {
    signals = { url, status: 0, contentLength: 0, title: '', description: '', canonical: '', h1: [], h2: [], robots: '', jsonLd: [], hasSchema: false, metaRobots: '', ogTags: {}, links: { internal: 0, external: 0 }, loadTime: 0, error: e instanceof Error ? e.message : 'Fetch failed' };
    changes.push(`Fetch failed: ${signals.error}`);
  }

  // Step 2: Run PSI
  console.log('     ⚡ Running PageSpeed...');
  const psi = runPSI(url);
  if (psi) {
    changes.push(`PSI score: ${psi.score}/100 (LCP: ${psi.lcp.toFixed(1)}s, CLS: ${psi.cls.toFixed(2)})`);
  } else {
    console.log('     ⚠️  PageSpeed unavailable (no API key?)');
  }

  // Step 2.5: GSC indexation check
  const gscStatus = checkGscIndexation(url);
  if (gscStatus) {
    changes.push(`GSC indexation: ${gscStatus.indexed ? '✅ Indexed' : '❌ Not indexed'}`);
  }

  // Step 2.6: Auto-generate schema if missing
  let autoSchema: AutoGeneratedSchema | null = null;
  if (!signals.hasSchema) {
    autoSchema = autoGenerateSchema(url, signals);
    if (autoSchema) {
      changes.push(`Auto-generated schema: ${autoSchema.type}`);
    }
  }

  // Step 2.7: Backlink analysis (domain-level)
  let backlinksResult: import('./backlinks/backlinks').BacklinkAnalysisResult | null = null;
  try {
    backlinksResult = BacklinkAnalyzer.analyze(url, { includeBing: true, includeMoz: false, includeCommonCrawl: true, limit: 50 });
    if (backlinksResult.totalBacklinks > 0) {
      changes.push(`Backlinks: ${backlinksResult.totalBacklinks} from ${backlinksResult.referringDomains} domains`);
    }
  } catch { /* backlinks optional */ }

  // Step 3: AI analysis (optional — works without it)
  let report = '';
  let data: TechnicalData | null = null;

  try {
    const available = (await import('./providers')).detectAll;
    const all = await available();
    const anyAuthed = all.some(a => a.authed);

    if (!anyAuthed) {
      console.log('     ⚠️  No AI provider available — showing raw signals only');
      report = `## SEO Audit Report — ${url}\n\n` +
        `**HTTP Status:** ${signals.status}\n` +
        `**Title:** ${signals.title || '(missing)'}\n` +
        `**Description:** ${signals.description || '(missing)'}\n` +
        `**Canonical:** ${signals.canonical || '(missing)'}\n` +
        `**H1 count:** ${signals.h1.length}\n` +
        `**H2 count:** ${signals.h2.length}\n` +
        `**Schema.org:** ${signals.hasSchema ? '✅ Found' : '❌ Not found'}\n` +
        `**Meta Robots:** ${signals.metaRobots || '(not set)'}\n` +
        `**Internal links:** ${signals.links.internal}\n` +
        `**External links:** ${signals.links.external}\n` +
        (psi ? `**PSI Score:** ${psi.score}/100 (LCP: ${psi.lcp.toFixed(1)}s, CLS: ${psi.cls.toFixed(2)})\n` : '') +
        `\n---\n*Set GEMINI_API_KEY or ANTHROPIC_API_KEY for AI-powered analysis.*\n`;
    } else {
      console.log('     🤖 AI analysis...');
      try {
        const provider = await (await import('./providers')).selectProvider();
        const result = await provider.chat({
          tier: 'synthesis',
          systemPrompt: SYSTEM_PROMPT,
          messages: [
            { role: 'user', content: `Audit this page. Signals:\n\n\`\`\`json\n${JSON.stringify({
              url: signals.url,
              status: signals.status,
              title: signals.title || '(missing)',
              description: signals.description || '(missing)',
              canonical: signals.canonical || '(missing)',
              h1Count: signals.h1.length,
              h2Count: signals.h2.length,
              hasSchema: signals.hasSchema || !!autoSchema,
              autoSchemaType: autoSchema?.type || null,
              jsonLdTypes: signals.jsonLd.length,
              metaRobots: signals.metaRobots || '(not set)',
              internalLinks: signals.links.internal,
              externalLinks: signals.links.external,
              h1: signals.h1,
              h2: signals.h2,
              gscIndexed: gscStatus?.indexed ?? null,
              gscLastCrawled: gscStatus?.lastCrawled ?? null,
              backlinks: backlinksResult ? {
                total: backlinksResult.totalBacklinks,
                referringDomains: backlinksResult.referringDomains,
                dofollowRatio: backlinksResult.dofollowRatio,
              } : null,
              performance: psi ? { score: psi.score, lcp: psi.lcp, cls: psi.cls } : null,
            }, null, 2)}\n\`\`\`` },
          ],
        });

        if (result?.text) {
          const extracted = extractDataBlock(result.text);
          report = extracted.body;
          if (extracted.data && isTechnicalData(extracted.data)) {
            data = extracted.data;
          }
          changes.push('AI audit analysis complete');
        } else {
          report = buildSignalsOnlyReport(url, signals, psi);
        }
      } catch (e) {
        console.log(`     ⚠️  AI provider failed — showing raw signals`);
        report = buildSignalsOnlyReport(url, signals, psi);
      }
    }
  } catch (e) {
    const msg = e instanceof Error ? e.message : 'Unknown error';
    report = `## Technical SEO Audit — ${url}\n\n**Error:** AI analysis failed — ${msg}\n\n### Raw Signals\n\`\`\`json\n${JSON.stringify(signals, null, 2)}\n\`\`\``;
    changes.push(`AI analysis failed: ${msg}`);
  }

  appendLog({ type: 'run', summary: `URL audit: ${url}`, detail: `${changes.length} data points`, changeCount: changes.length });
  writeBrain({ lastRun: { timestamp: new Date().toISOString(), duration: 0, postsProcessed: 1, errors: report.includes('Error') ? 1 : 0, totalChanges: changes.length } });

  // Record in vault if this isn't just an error stub
  if (signals.url) {
    try {
      const { computeAuditScore, computeSeveritySignals, recordSignal, initBrain, recordAuditRun } = await import('./brain/brain-manager');
      initBrain();
      const computedSignals = computeSeveritySignals(signals, psi);
      const score = computeAuditScore(signals, psi);
      for (const s of computedSignals) {
        recordSignal(url, s.id, s.label, s.severity, s.detail);
      }
      recordAuditRun(url, report, score, computedSignals.length);
    } catch {}
  }

  return { url, signals, performance: psi, report, data, changes };
}