#!/usr/bin/env node

/**
 * seo-llms-txt generator — SeoFlow extension
 *
 * Detects project data sources and scaffold the structure for
 * dynamic /llms.txt and /llms-full.txt Next.js route handlers.
 *
 * After scaffolding, the AI agent (following the skill instructions
 * in skills/seo-llms-txt/SKILL.md) fills in the actual content by
 * reading the project's data structures.
 *
 * Usage:
 *   node .seoflow/generate-llms-txt.mjs [project-path]
 */

import fs from 'node:fs';
import path from 'node:path';

const cwd = process.argv[2] || process.cwd();

function walkDir(dir, acc) {
  try {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory() && !entry.name.startsWith('.') && entry.name !== 'node_modules' && entry.name !== '.next') {
        walkDir(full, acc);
      } else if (entry.isFile()) {
        acc.push(full);
      }
    }
  } catch { /* skip */ }
}

function detect(base) {
  const allFiles = [];
  walkDir(base, allFiles);
  const rel = allFiles.map((f) => path.relative(base, f));

  const imports = [];
  if (rel.some((p) => p.endsWith('metadata.ts') || p.endsWith('seo.ts'))) imports.push('@/lib/metadata');
  if (rel.some((p) => p.endsWith('products.ts'))) imports.push('@/lib/products');
  if (rel.some((p) => p.endsWith('services.ts'))) imports.push('@/lib/data/services');
  if (rel.some((p) => p.endsWith('mdx.ts'))) imports.push('@/lib/mdx');

  // Extract site name
  let name = 'Your Site';
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(base, 'package.json'), 'utf-8'));
    name = pkg.name || name;
  } catch {}

  // Extract site URL
  let url = 'https://yoursite.com';
  for (const f of [path.join(base, 'lib', 'metadata.ts'), path.join(base, 'app', 'layout.tsx')]) {
    try {
      const m = fs.readFileSync(f, 'utf-8').match(/siteUrl\s*=\s*['"]([^'"]+)['"]/);
      if (m) url = m[1];
    } catch {}
  }

  return {
    name: name.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
    url,
    imports,
    hasAppRouter: fs.existsSync(path.join(base, 'app')),
    fileCount: allFiles.length
  };
}

function scaffoldRoute(info, isFull) {
  const suffix = isFull ? '-full' : '';
  const routeDir = path.join(cwd, 'app', `llms${suffix}.txt`);
  const routePath = path.join(routeDir, 'route.ts');

  const impLines = info.imports.map((m) => {
    if (m.includes('metadata')) return "import { siteUrl, siteName } from '" + m + "';";
    if (m.includes('products')) return "import { products } from '" + m + "';";
    if (m.includes('services')) return "import { services, serviceGroups } from '" + m + "';";
    if (m.includes('mdx')) return "import { getAllPosts } from '" + m + "';";
    return "import {} from '" + m + "';";
  });

  const code = [
    '// Dynamic /llms' + suffix + '.txt — generated by seo-llms-txt',
    '// Edit the sections below to match your project data structures.',
    '',
    ...impLines,
    '',
    'function formatDate(dateString: string): string {',
    "  return new Intl.DateTimeFormat('en-US', {",
    "    month: 'short',",
    "    day: 'numeric',",
    "    year: 'numeric'",
    '  }).format(new Date(dateString));',
    '}',
    '',
    'export async function GET(): Promise<Response> {',
  ];

  if (info.imports.some((i) => i.includes('mdx'))) {
    code.push('  const posts = getAllPosts();');
  }
  if (info.imports.some((i) => i.includes('products'))) {
    code.push("  const available = products.filter((p) => p.status === 'available');");
    code.push("  const comingSoon = products.filter((p) => p.status === 'coming-soon');");
  }

  code.push('');

  // Generate the sections
  const sections = [];

  // Scaffold based on detected sources
  sections.push("    `# ${info.name}${isFull ? ' \u2014 Full AI Reference' : ''}`,");
  sections.push("    ''");

  if (isFull) {
    sections.push("    '> Complete reference for AI agents working with this site.',");
    sections.push("    ''");
    sections.push("    '---'");
    sections.push("    ''");
  }

  sections.push("    '## Core Pages',");
  sections.push("    ''");
  sections.push(`    \`- [Home](${info.url}/)\`,`);
  sections.push("    ''");

  if (info.imports.some((i) => i.includes('services'))) {
    sections.push("    '## Services',");
    sections.push("    ''");
    sections.push("    '// Iterate over your service data source',");
    sections.push("    ''");
  }

  if (info.imports.some((i) => i.includes('products'))) {
    sections.push("    '## Products',");
    sections.push("    ''");
    sections.push("    '// Iterate over your products data source',");
    sections.push("    ''");
  }

  if (info.imports.some((i) => i.includes('mdx'))) {
    sections.push("    '## Blog',");
    sections.push("    ''");
    sections.push("    '// Iterate over your blog posts',");
    sections.push("    ''");
  }

  if (isFull) {
    sections.push("    '## Technical Architecture',");
    sections.push("    ''");
    sections.push("    '- **Framework**: Next.js',");
    sections.push("    '- **Language**: TypeScript',");
    sections.push("    ''");
    sections.push("    '## AI Agent Guidance',");
    sections.push("    ''");
    sections.push("    '- Run `npm run dev` for development',");
    sections.push("    '- Run `npm run lint` for linting',");
    sections.push("    '- Run `npm run typecheck` to verify TypeScript',");
    sections.push("    ''");
  }

  const code_end = [
    '  ];',
    '',
    "",
    "  return new Response(out.join('\\n'), {",
    '    headers: {',
    "      'Content-Type': 'text/plain; charset=utf-8',",
    "      'Cache-Control': 'public, max-age=3600, s-maxage=3600'",
    '    }',
    '  });',
    '}',
    '',
  ];

  // Combine: scaffold + sections + end
  const allCode = code.join('\n') + '\n  const out: string[] = [\n' + sections.join('\n') + '\n' + code_end.join('\n');

  return { routePath, code: allCode };
}

// --- Main ---

console.log('\n\u{1F50D} Scanning project...\n');
const info = detect(cwd);

console.log('  Site:      ' + info.name);
console.log('  URL:       ' + info.url);
console.log('  Router:    ' + (info.hasAppRouter ? 'App Router' : 'unknown'));
console.log('  Imports:   ' + (info.imports.length ? info.imports.join(', ') : 'none detected'));
console.log('  Files:     ' + info.fileCount + ' total');
console.log('');

if (!info.hasAppRouter) {
  console.error('App Router not detected. Create a static file in public/ instead.');
  process.exit(1);
}

const results = [];
for (const full of [false, true]) {
  const { routePath, code } = scaffoldRoute(info, full);
  fs.mkdirSync(path.dirname(routePath), { recursive: true });
  fs.writeFileSync(routePath, code);
  results.push(routePath);
  console.log('  Created ' + (full ? '/llms-full.txt' : '/llms.txt'));
}

console.log('');
console.log('Generated:');
results.forEach((p) => console.log('  ' + p));
console.log('');
console.log('Next: The AI agent will fill in the dynamic content based on');
console.log('your project data structures. Run `npm run lint && npm run typecheck`');
console.log('to verify after content is added.');
console.log('');
